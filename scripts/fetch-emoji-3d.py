"""Download Microsoft Fluent Emoji 3D (MIT) images for exactly the emojis 25 uses.

Run from the repo root:  python3 scripts/fetch-emoji-3d.py   (needs: pip install emoji pillow)
Writes public/assets/emoji3d/<codepoints>.webp and src/lib/emoji3d.ts.
"""
import glob
import io
import os
import urllib.parse
import urllib.request

import emoji
from PIL import Image

RAW = "https://raw.githubusercontent.com/microsoft/fluentui-emoji/main/assets/"
OUT = "public/assets/emoji3d"
os.makedirs(OUT, exist_ok=True)

# A few emojis whose Fluent folder name differs from the standard short name.
ALIASES = {
    "😂": ["Face with tears of joy"],
    "❤️": ["Red heart"],
    "❤": ["Red heart"],
    "👍": ["Thumbs up"],
    "✍️": ["Writing hand"],
    "✍": ["Writing hand"],
    "🫡": ["Saluting face"],
    "🏝️": ["Desert island"],
    "🏝": ["Desert island"],
    "🗺️": ["World map"],
    "🗺": ["World map"],
    "🕵️": ["Detective"],
    "🕵": ["Detective"],
    "🤗": ["Hugging face"],
    "🧟": ["Man zombie"],
    "😵": ["Face with spiral eyes"],
}

found = {}
for p in glob.glob("src/**/*.ts*", recursive=True):
    if p.endswith("emoji3d.ts"):
        continue
    for m in emoji.emoji_list(open(p, encoding="utf-8").read()):
        if m["emoji"].strip("\ufe0f") in ("©", "®", "™", "🇮🇳"):
            continue  # text symbols / flags (Fluent has no flags) stay as text
        found.setdefault(m["emoji"], p)


def key(e):
    return "-".join(f"{ord(c):x}" for c in e if ord(c) not in (0xFE0F, 0xFE0E))


def names(e):
    out = list(ALIASES.get(e, []))
    base = emoji.demojize(e, language="en").strip(":")
    if base and base != e:
        n = base.replace("_", " ")
        out += [n[0].upper() + n[1:], n.title()]
    return list(dict.fromkeys(out))


def get(url):
    try:
        with urllib.request.urlopen(url, timeout=20) as r:
            return r.read()
    except Exception:
        return None


ok, miss = {}, []
for e in sorted(found):
    k = key(e)
    dst = f"{OUT}/{k}.webp"
    if os.path.exists(dst):
        ok[e] = k
        continue
    data = None
    for n in names(e):
        folder = urllib.parse.quote(n)
        file = n.lower().replace(" ", "_").replace("'", "").replace("’", "").replace(":", "").replace(",", "")
        for path in (
            f"{folder}/3D/{urllib.parse.quote(file)}_3d.png",
            f"{folder}/Default/3D/{urllib.parse.quote(file)}_3d_default.png",
        ):
            data = get(RAW + path)
            if data:
                break
        if data:
            break
    if not data:
        miss.append((e, names(e), found[e]))
        continue
    im = Image.open(io.BytesIO(data)).convert("RGBA").resize((160, 160), Image.LANCZOS)
    im.save(dst, "WEBP", quality=86, method=6)
    ok[e] = k

lines = [
    "/** Emoji → Fluent Emoji 3D image (MIT, Microsoft). Generated by scripts/fetch-emoji-3d.py. */",
    "export const EMOJI3D: Record<string, string> = {",
]
for e, k in sorted(ok.items(), key=lambda x: x[1]):
    lines.append(f'  "{e}": "{k}",')
lines.append("};")
open("src/lib/emoji3d.ts", "w", encoding="utf-8").write("\n".join(lines) + "\n")
print("done", len(ok), "missing", len(miss))
for m in miss:
    print("MISS", m)
